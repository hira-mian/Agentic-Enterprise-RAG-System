"""Collect results/*/summary.json into a Markdown results table (results/RESULTS.md)."""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from enterprise_rag.evaluate import RESULTS_DIR  # noqa: E402

COLUMNS = [
    ("hit@2", "Hit@2"),
    ("recall@2", "Recall@2"),
    ("all@2", "All-evidence@2"),
    ("mrr@2", "MRR@2"),
    ("recall@10", "Recall@10"),
    ("accuracy", "Answer acc."),
    ("exact_match", "EM"),
    ("token_f1", "Token F1"),
]
TYPES = ["inference_query", "comparison_query", "temporal_query", "null_query"]


def fmt(summary_part: dict, key: str) -> str:
    v = summary_part.get(key)
    return "—" if v is None else f"{v:.3f}"


def main() -> None:
    summaries = [json.loads(p.read_text()) for p in sorted(RESULTS_DIR.glob("*/summary.json"))]
    lines = ["# Baseline results", "",
             "Generated by `python scripts/make_results_table.py` from `results/*/summary.json`.",
             "Retrieval metrics are computed on queries with evidence (null queries excluded);",
             "answer metrics on all queries of the split. `—` = not applicable / not run.", "",
             "## Overall", "",
             "| Run | Split | N | " + " | ".join(c[1] for c in COLUMNS) + " |",
             "|---|---|---|" + "---|" * len(COLUMNS)]
    for s in summaries:
        o = s["overall"]
        lines.append(f"| `{s['run']}` | {s['split']} | {o['n']} | " + " | ".join(fmt(o, c[0]) for c in COLUMNS) + " |")

    for metric, title in (("recall@2", "Recall@2"), ("accuracy", "Answer accuracy")):
        lines += ["", f"## {title} by question type", "",
                  "| Run | " + " | ".join(TYPES) + " |", "|---|" + "---|" * len(TYPES)]
        for s in summaries:
            bt = s["by_question_type"]
            if all(metric not in bt.get(t, {}) for t in TYPES):
                continue
            lines.append(f"| `{s['run']}` | " + " | ".join(fmt(bt.get(t, {}), metric) for t in TYPES) + " |")

    out = RESULTS_DIR / "RESULTS.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nWrote {out}")


if __name__ == "__main__":
    main()
